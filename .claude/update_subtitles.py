path = r'C:/Users/david/kiidschool/index.html'
with open(path, 'r', encoding='utf-8') as f:
    s = f.read()

updated = 0
for name, info in camps.items():
    if 'rename_to' in info:
        s = s.replace(
            '<div class="card-name">{}</div>'.format(name),
            '<div class="card-name">{}</div>'.format(info['rename_to']),
            1,
        )

    real_name = info.get('rename_to', name)
    pat_sub = re.compile(
        r'(<div class="card-name">' + re.escape(real_name) + r'</div>\s*)'
        r'<div class="card-subtitle">[^<]*</div>',
        re.DOTALL,
    )
    if not pat_sub.search(s):
        print('X subtitle miss:', real_name)
        continue
    s = pat_sub.sub(
        lambda m: m.group(1) + '<div class="card-subtitle">{}</div>'.format(info['tagline']),
        s,
        count=1,
    )

    suitable_html = ''.join('<li>{}</li>'.format(x) for x in info['suitable'])
    detail_block = (
        '<button class="card-detail-toggle" onclick="toggleDetail(this)">'
        '<span>📖 营期亮点 · 适合人群</span><span class="arrow">▼</span></button>\n'
        '    <div class="card-detail-panel">\n'
        '      <div class="detail-section">\n'
        '        <h5>产品亮点</h5>\n'
        '        <p>' + info['highlights'] + '</p>\n'
        '      </div>\n'
        '      <div class="detail-section">\n'
        '        <h5>适合人群</h5>\n'
        '        <ul>' + suitable_html + '</ul>\n'
        '      </div>\n'
        '      <div class="detail-tip">客服不做推荐 · 仅供家长参考 · 让孩子自己选感兴趣的主题 🌟</div>\n'
        '    </div>\n    '
    )

    card_pat = re.compile(
        r'(<div class="card-name">' + re.escape(real_name) + r'</div>.*?)<button class="card-qr-toggle"',
        re.DOTALL,
    )
    s2, n = card_pat.subn(
        lambda m: m.group(1) + detail_block + '<button class="card-qr-toggle"',
        s,
        count=1,
    )
    if n != 1:
        print('X qr-toggle miss:', real_name)
        continue
    s = s2
    updated += 1
    print('OK', real_name)

with open(path, 'w', encoding='utf-8') as f:
    f.write(s)
print('\nUpdated {}/{} cards'.format(updated, len(camps)))
